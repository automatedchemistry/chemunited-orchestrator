// Copies the type declarations an editor needs for a project's
// customizations/ui/ into the Python package (chemunited_workflow/ui/types/),
// from where `chemunited-workflow ui init` copies them into the project:
// Vue's own declarations (csstype and the compiler stubbed) and chemunited.d.ts.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const modules = join(root, 'node_modules')
const out = join(root, '..', 'chemunited_workflow', 'ui', 'types')

function put(target, text) {
  const file = join(out, target)
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, text)
}

function copy(source, target) {
  put(target, readFileSync(join(modules, source), 'utf8'))
}

rmSync(out, { recursive: true, force: true })
copy('vue/dist/vue.d.mts', 'vue/index.d.ts')
copy('@vue/runtime-dom/dist/runtime-dom.d.ts', '@vue/runtime-dom/index.d.ts')
copy('@vue/runtime-core/dist/runtime-core.d.ts', '@vue/runtime-core/index.d.ts')
copy('@vue/reactivity/dist/reactivity.d.ts', '@vue/reactivity/index.d.ts')
copy('@vue/shared/dist/shared.d.ts', '@vue/shared/index.d.ts')
put('@vue/compiler-dom/index.d.ts', [
  '// Stub: the one type vue\'s compile() mentions; custom pages never call it.',
  'export type CompilerOptions = Record<string, unknown>',
  '',
].join('\n'))
put('csstype/index.d.ts', [
  '// Stub for csstype (~900 KB): style objects are loose records here.',
  'export interface Properties<TLength = string | 0, TTime = string> { [property: string]: unknown }',
  'export interface PropertiesHyphen<TLength = string | 0, TTime = string> { [property: string]: unknown }',
  '',
].join('\n'))
copy('../types/chemunited.d.ts', 'chemunited.d.ts')

const { version } = JSON.parse(readFileSync(join(modules, 'vue', 'package.json'), 'utf8'))
put('README.md', [
  `Type declarations for editing customizations/ui/ (Vue ${version} and the chemunited module).`,
  'Generated by .web-chemunited/scripts/emit-ui-types.mjs on every dashboard build; do not edit.',
  '',
].join('\n'))
console.log(`UI types (vue ${version}) written to ${out}`)
